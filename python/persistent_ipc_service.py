def create_socket_path(explicit: Optional[str]) -> Tuple[str, Optional[str]]:
    """Returns (socket path, private directory to remove on stop or None).

    Without an explicit path a fresh 0700 directory is made (under XDG_RUNTIME_DIR when set), so
    no other local user can pre-create, replace or connect to the socket. An explicit path must
    sit in a directory owned by this user that is not group/world-writable (not /tmp itself).
    """
    if explicit:
        parent = os.path.dirname(os.path.abspath(explicit))
        st = os.stat(parent)
        foreign = hasattr(os, "getuid") and st.st_uid != os.getuid()
        if foreign or stat.S_IMODE(st.st_mode) & 0o022:
            raise SystemExit(
                f"[PersistentIPC] Refusing METALLIX_IPC_SOCK={explicit!r}: its directory must be owned by "
                "this user and not group/world-writable. Unset it to get a private 0700 directory.")
        return explicit, None
    base = os.environ.get("XDG_RUNTIME_DIR")
    private_dir = tempfile.mkdtemp(prefix="metallix-ipc-", dir=base if base and os.path.isdir(base) else None)
    os.chmod(private_dir, 0o700)
    return os.path.join(private_dir, "ipc.sock"), private_dir


def _frame(status: int, body_obj: Any, token: Optional[str], nonce: Optional[str]) -> bytes:
    body = json.dumps(body_obj).encode("utf-8")
    digest = body_digest(body)
    head: Dict[str, Any] = {"v": 2, "status": int(status), "len": len(body), "sha256": digest}
    if nonce is not None and token:
        head["mac"] = response_mac(token, nonce, status, len(body), digest)
    return json.dumps(head).encode("utf-8") + b"\n" + body


# =========================================================================
# 1. UNIX Domain Socket IPC Server (one framed request per connection)
# =========================================================================
# Request:  head line {"v": 2, "ts", "nonce", "len", "sha256", "mac"} + "\n" + exactly len body bytes
#           mac = request_mac(token, "UNIX", "/", ts, nonce, len, sha256), verified before the body.
# Response: head line {"v": 2, "status", "len", "sha256", "mac"} + "\n" + body.
#           status 200 = executed (any exitCode); >= 400 = refused before execution. Only responses
#           to authenticated requests are signed.
class UnixIPCServer:
    def __init__(self, sock_path: str, reg: ConcurrentModuleRegistry, token: Optional[str] = None,
                 private_dir: Optional[str] = None):
        self.sock_path = sock_path
        self.private_dir = private_dir
        self.reg = reg
        self.token = token
        self.nonces = NonceCache()
        self.preauth = threading.BoundedSemaphore(PREAUTH_SLOTS)
        self.sock = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        self.running = False
        self.thread = None

    def bind(self):
        """Creates the owner-only socket and listens; connections wait until serve()."""
        if self.private_dir is None and os.path.lexists(self.sock_path):
            os.remove(self.sock_path)  # explicit path in a private directory: a stale socket of ours

        # Owner-only from creation (umask) and explicitly afterwards; never world-writable.
        old_umask = os.umask(0o177)
        try:
            self.sock.bind(self.sock_path)
        finally:
            os.umask(old_umask)
        os.chmod(self.sock_path, 0o600)
        self.sock.listen(64)

    def serve(self):
        self.running = True
        self.thread = threading.Thread(target=self._accept_loop, daemon=True)
        self.thread.start()
        sys.stderr.write(f"[PersistentIPC] UNIX domain socket listening at {self.sock_path}\n")

    def start(self):
        self.bind()
        self.serve()

    def _accept_loop(self):
        while self.running:
            try:
                conn, _ = self.sock.accept()
                threading.Thread(target=self._handle_client, args=(conn,), daemon=True).start()
            except Exception:
                if not self.running:
                    break

    @staticmethod
    def _read_head(conn: socket.socket, deadline: float) -> Tuple[bytes, bytes]:
        """Reads the head line (bounded, newline searched only in new data)."""
        buf = bytearray()
        while True:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                raise IPCRequestRejected(408, "REQUEST_TIMEOUT", "IPC request head not received in time")
            conn.settimeout(remaining)
            try:
                chunk = conn.recv(4096)
            except socket.timeout:
                raise IPCRequestRejected(408, "REQUEST_TIMEOUT", "IPC request head not received in time")
            if not chunk:
                raise IPCRequestRejected(400, "INVALID_FRAME", "Connection closed before the request head")
            start = len(buf)
            buf += chunk
            i = buf.find(b"\n", start)
            if i >= 0:
                return bytes(buf[:i]), bytes(buf[i + 1:])
            if len(buf) > MAX_HEAD_BYTES:
                raise IPCRequestRejected(413, "HEAD_TOO_LARGE", "IPC request head too large")

    def _handle_client(self, conn: socket.socket):
        if not self.preauth.acquire(blocking=False):
            conn.close()  # too many unauthenticated connections
            return
        holding = True
        nonce = None
        try:
            try:
                head_line, rest = self._read_head(conn, time.monotonic() + PREAUTH_DEADLINE_S)
                try:
                    head = json.loads(head_line.decode("utf-8"))
                except Exception:
                    raise IPCRequestRejected(400, "INVALID_FRAME", "Invalid IPC frame head")
                if not isinstance(head, dict) or head.get("v") != 2:
                    raise IPCRequestRejected(401, "UNAUTHORIZED", "Missing or malformed IPC authentication")
                length = head.get("len")
                if isinstance(length, bool) or not isinstance(length, int) or length <= 0:
                    raise IPCRequestRejected(400, "INVALID_FRAME", "Invalid IPC frame length")
                if length > MAX_BODY_BYTES:
                    raise IPCRequestRejected(413, "PAYLOAD_TOO_LARGE", f"Body larger than {MAX_BODY_BYTES} bytes")
                verify_request(self.token, "UNIX", "/", head.get("ts"), head.get("nonce"), head.get("mac"),
                               length, head.get("sha256"), self.nonces)
                nonce = head["nonce"]
                self.preauth.release()
                holding = False

                pending = [rest]

                def read(n: int) -> bytes:
                    if pending[0]:
                        part, pending[0] = pending[0][:n], pending[0][n:]
                        return part
                    return conn.recv(n)

                conn.settimeout(CONNECTION_IDLE_TIMEOUT_S)
                body = read_body_checked(read, length, head["sha256"], time.monotonic() + BODY_DEADLINE_S)
                try:
                    req = json.loads(body.decode("utf-8"))
                except Exception:
                    req = None
                if not isinstance(req, dict):
                    raise IPCRequestRejected(400, "INVALID_REQUEST", "Request body must be a JSON object")
            except IPCRequestRejected as rejected:
                conn.sendall(_frame(rejected.status, {"error": rejected.message, "code": rejected.code},
                                    self.token, nonce))
                return

            action = req.get("action", "execute")
            req_id = req.get("id")
            if action == "status":
                result = self.reg.get_status()
            elif action == "ping":
                result = {"pong": True}
            else:
                try:
                    script, payload, args, timeout_ms = validate_exec_request(req)
                    resolve_script_path(self.reg.script_dir, script)
                except IPCRequestRejected as rejected:
                    result = {"error": rejected.message, "code": rejected.code}
                    if req_id is not None:
                        result["id"] = req_id
                    conn.sendall(_frame(rejected.status, result, self.token, nonce))
                    return
                result = self.reg.execute_script(script, payload, args, timeout_ms)
            if req_id is not None:
                result["id"] = req_id
            conn.sendall(_frame(200, result, self.token, nonce))
        except (ConnectionResetError, BrokenPipeError, socket.timeout):
            pass
        except Exception as e:
            sys.stderr.write(f"[PersistentIPC] Client connection error: {e}\n")
        finally:
            if holding:
                self.preauth.release()
            try:
                conn.close()
            except Exception:
                pass

    def stop(self):
        self.running = False
        try:
            self.sock.close()
        except Exception:
            pass
        if os.path.lexists(self.sock_path):
            try:
                os.remove(self.sock_path)
            except OSError:
                pass
        if self.private_dir:
            shutil.rmtree(self.private_dir, ignore_errors=True)


