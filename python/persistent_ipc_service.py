#!/usr/bin/env python3
"""
MetalliX Persistent Python HPC Microservice & IPC Worker Daemon
Maintains scientific calculation modules warm in memory, bypassing Python startup & module import overhead.
Exposes:
 1. UNIX Domain Socket IPC (POSIX) in a private 0700 directory for direct Node.js streaming.
 2. Loopback HTTP Microservice on an ephemeral port: always on Windows (no UNIX socket there), on
    POSIX only when METALLIX_IPC_HTTP=1.
Both channels and their actual address are announced in the ready message on stdout; the Node
supervisor (server/processOrchestrator.ts) only talks to channels its own child announced.

Security model (both channels, protocol "metallix-ipc-v2"):
 - The per-spawn shared secret METALLIX_IPC_TOKEN (>= 32 chars, generated by the Node supervisor,
   passed through the environment) never travels on the wire. A request's MAC covers method, path,
   timestamp, nonce, body length and SHA-256(body) and is verified from the headers BEFORE any body
   byte is read; the body is then streamed and must match the hash. Each response carries
   HMAC(token, nonce, status, length, SHA-256(body)). A listener without the token can neither
   reuse a request (nonce replay cache, +-120 s window) nor forge a response the client accepts.
 - Unauthenticated connections are bounded: at most PREAUTH_SLOTS at a time, each with a
   PREAUTH_DEADLINE_S deadline for the request line and headers; one request per connection.
 - The service refuses to start without a token, before any warm-up.
 - HTTP: no CORS headers; requests with an ``Origin`` header (browsers) are rejected; ``Host`` must
   name the bound loopback address and port (DNS rebinding); POST bodies must be
   ``application/json`` and at most MAX_BODY_BYTES. Windows binds with SO_EXCLUSIVEADDRUSE.
 - Scripts: only ``python/<name>.py`` or ``<name>.py`` where <name> is in ALLOWED_SCRIPT_NAMES,
   resolved with realpath and required to stay in SCRIPT_DIR.
 - The UNIX socket lives in a fresh 0700 directory (mkdtemp, under XDG_RUNTIME_DIR when set) and
   is created 0600; on POSIX a socket that cannot be created is fatal, not a silent HTTP-only mode.
 - Only loopback addresses are bound (127.0.0.0/8, localhost, ::1); anything else is refused.
 - With METALLIX_IPC_STDIN_WATCH=1 the daemon exits (and removes its socket directory) when its
   stdin reaches EOF, i.e. when the supervising Node process is gone.
"""

