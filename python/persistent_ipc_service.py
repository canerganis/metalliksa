def _exit_when_parent_dies() -> None:
    """Pool workers end when their parent (the daemon) is gone, also after a hard kill of the
    daemon (which would otherwise leave them running, each holding its imports and caches)."""
    parent = multiprocessing.parent_process()
    if parent is None:
        return

    def watch():
        try:
            parent.join()
        except Exception:
            return
        os._exit(0)

    threading.Thread(target=watch, daemon=True, name="metallix-worker-parent-watch").start()


def _parent_uname():
    """The parent's platform.uname(), handed to each worker so its imports never have to query it."""
    import platform
    return platform.uname()


def _adopt_parent_uname(uname) -> None:
    """Seeds platform's per-process uname cache in a spawned worker.

    Libraries imported during warm-up (numpy, scipy) call platform.uname(). On Windows it first asks WMI
    and, when that fails (it does under heavy machine load), falls back to ``cmd /c ver`` through
    subprocess. That WMI-failure -> subprocess path is what the WinError 6 / "Worker process died during
    execution" flake correlated with (an audit hook showed a standard handle being flipped right after
    the ``ver`` Popen, and a queue handle number then failing); the exact handle-closing site is not
    confirmed. A seeded cache skips both WMI and ``ver``, so the whole path is removed from worker
    start-up. The attribute is CPython-private; when it is absent this is a no-op.
    """
    import platform
    if uname is not None and hasattr(platform, "_uname_cache"):
        platform._uname_cache = uname


def _worker_init(script_dir: str, module_names: list, uname=None):
    """Initializes each process pool worker by adding paths and pre-warming modules."""
    _adopt_parent_uname(uname)  # before any import that may call platform.uname()
    _exit_when_parent_dies()
    if script_dir not in sys.path:
        sys.path.insert(0, script_dir)
    global _worker_modules, _worker_compiled_cache
    _worker_modules = {}
    _worker_compiled_cache = {}

    for mod_name in module_names:
        # realpath: the key execute_script submits (resolve_script_path returns realpaths).
        py_file = os.path.realpath(os.path.join(script_dir, f"{mod_name}.py"))
        try:
            mod = __import__(mod_name)
            _worker_modules[mod_name] = mod
            if os.path.exists(py_file):
                with open(py_file, "r", encoding="utf-8") as f:
                    _worker_compiled_cache[py_file] = compile(f.read(), py_file, "exec")
        except Exception:
            pass


def _worker_run_script(full_path: str, input_str: str, args: list) -> Dict[str, Any]:
    """
    Executes a script inside an isolated worker process.
    Guarantees independent sys.stdin / sys.stdout / sys.stderr and full CPU concurrency.
    """
    global _worker_compiled_cache

    if full_path not in _worker_compiled_cache:
        try:
            with open(full_path, "r", encoding="utf-8") as f:
                _worker_compiled_cache[full_path] = compile(f.read(), full_path, "exec")
        except Exception as e:
            return {
                "stdout": "",
                "stderr": f"Compilation failed: {str(e)}",
                "exitCode": 1,
            }

    compiled = _worker_compiled_cache[full_path]

    old_stdin = sys.stdin
    old_stdout = sys.stdout
    old_stderr = sys.stderr
    old_argv = sys.argv

    captured_stdout = io.StringIO()
    captured_stderr = io.StringIO()
    sys.stdin = io.StringIO(input_str)
    sys.stdout = captured_stdout
    sys.stderr = captured_stderr
    sys.argv = [os.path.basename(full_path)] + (args or [])

    env = {
        "__name__": "__main__",
        "__file__": full_path,
        "__package__": None,
    }

    exit_code = 0
    try:
        exec(compiled, env)
    except SystemExit as se:
        exit_code = se.code if isinstance(se.code, int) else 0
    except Exception:
        exit_code = 1
        captured_stderr.write(traceback.format_exc())
    finally:
        sys.stdin = old_stdin
        sys.stdout = old_stdout
        sys.stderr = old_stderr
        sys.argv = old_argv

    return {
        "stdout": captured_stdout.getvalue(),
        "stderr": captured_stderr.getvalue(),
        "exitCode": exit_code,
    }


def _worker_noop(delay: float) -> int:
    """Pre-warm task: makes the pool start (and initialise) its worker processes."""
    time.sleep(delay)
    return os.getpid()


_MP_CONTEXT = None


def _pool_mp_context():
    """Workers start from a fresh interpreter instead of a fork of this process (whose memory holds
    the token). POSIX: forkserver, preloaded with this script (guarded, no registry) and the warm
    modules, so every worker shares those imports copy-on-write; the forkserver itself is started
    from the already-scrubbed environment. Windows: spawn (each worker imports in _worker_init)."""
    global _MP_CONTEXT
    if _MP_CONTEXT is None:
        if os.name != "nt" and "forkserver" in multiprocessing.get_all_start_methods():
            ctx = multiprocessing.get_context("forkserver")
            preload = (["__main__"] if __name__ == "__main__" else []) + list(WARM_MODULE_NAMES)
            ctx.set_forkserver_preload(preload)
            _MP_CONTEXT = ctx
        else:
            _MP_CONTEXT = multiprocessing.get_context("spawn")
    return _MP_CONTEXT


class _AffinityTicket:
    __slots__ = ("key", "superseded")

    def __init__(self, key: Optional[str]):
        self.key = key
        self.superseded = False


class _AffinityLane:
    """Serial dispatcher for one affinity script.

    At most ONE job is inside the lane's single-worker pool at any time; waiting requests stay in
    this lane's own queue, where they can be superseded (a newer request with the same
    supersedeKey, e.g. the next slider position from the same Studio) or time out without ever
    running. Consequences, by construction:
      * a request that times out while queued is never computed later (no zombie jobs);
      * the running job is the only work in the pool, so when it exceeds its caller's budget the
        worker is killed and replaced immediately, whatever else is queued (a hung pycalphad call
        cannot block the lane);
      * a worker death affects only the one running request.
    Recycling is generation-aware: a handler replaces the pool only if it is still the pool its job
    ran in, so a stale handler never kills a replacement.
    ``submit_args`` is (callable, *args) for the pool; tests pass a thread pool factory.
    """

    def __init__(self, name: str, factory, prestart_args: Optional[tuple] = None):
        self.name = name
        self._factory = factory
        self._prestart_args = prestart_args
        self.cond = threading.Condition()
        self.pool = None
        self.generation = 0
        self.waiting: list = []
        self.running: Optional[_AffinityTicket] = None
        self.stats = {"completed": 0, "superseded": 0, "queueTimeouts": 0, "runTimeouts": 0,
                      "workerDeaths": 0, "recycles": 0}

    # -- pool management (callers hold no lock; these take it) --
    def _ensure_pool(self):
        with self.cond:
            if self.pool is None:
                self.pool = self._factory()
                self.generation += 1
                if self._prestart_args is not None:
                    try:
                        self.pool.submit(*self._prestart_args)
                    except Exception:
                        pass
            return self.pool, self.generation

    def recycle(self, generation: int) -> bool:
        """Kill the pool of ``generation`` and start a replacement; no-op if it was already replaced."""
        with self.cond:
            if self.pool is None or generation != self.generation:
                return False
            old, self.pool = self.pool, None
            self.stats["recycles"] += 1
        ConcurrentModuleRegistry._kill_pool(old)
        self._ensure_pool()  # replacement starts now, not on the next request
        return True

    def prestart(self) -> None:
        self._ensure_pool()

    def shutdown(self) -> None:
        with self.cond:
            old, self.pool = self.pool, None
            self.generation += 1
            self.cond.notify_all()
        if old is not None:
            ConcurrentModuleRegistry._kill_pool(old)

    def snapshot(self) -> Dict[str, Any]:
        with self.cond:
            return {"queued": sum(1 for t in self.waiting if not t.superseded),
                    "running": self.running is not None, "generation": self.generation, **self.stats}

    # -- one request --
    def run(self, submit_args: tuple, timeout_s: float, key: Optional[str],
            recycle_after: Optional[Any] = None) -> Dict[str, Any]:
        """``recycle_after(result) -> bool``, when given, is asked about a completed result while the job still
        holds the lane; True replaces the worker it ran in before the next queued request starts."""
        t0 = time.perf_counter()
        deadline = t0 + timeout_s
        ticket = _AffinityTicket(key)
        with self.cond:
            if key is not None:
                for other in self.waiting:
                    if other.key == key and not other.superseded:
                        other.superseded = True
                        self.stats["superseded"] += 1
            self.waiting.append(ticket)
            self.cond.notify_all()
            while True:
                if ticket.superseded:
                    self.waiting.remove(ticket)
                    self.cond.notify_all()
                    return {"outcome": "superseded", "queueWaitMs": _ms_since(t0)}
                head = next((t for t in self.waiting if not t.superseded), None)
                if self.running is None and head is ticket:
                    break
                remaining = deadline - time.perf_counter()
                if remaining <= 0:
                    ahead = sum(1 for t in self.waiting[: self.waiting.index(ticket)] if not t.superseded)
                    ahead += 1 if self.running is not None else 0
                    self.waiting.remove(ticket)
                    self.stats["queueTimeouts"] += 1
                    self.cond.notify_all()
                    return {"outcome": "queue-timeout", "ahead": ahead, "queueWaitMs": _ms_since(t0)}
                self.cond.wait(remaining)
            self.waiting.remove(ticket)
            self.running = ticket
        queue_ms = _ms_since(t0)
        try:
            pool, generation = self._ensure_pool()
            try:
                future = pool.submit(*submit_args)
            except (BrokenProcessPool, RuntimeError):
                # not submitted, so not executed: replace the pool and submit once more
                self.recycle(generation)
                pool, generation = self._ensure_pool()
                future = pool.submit(*submit_args)
            try:
                res = future.result(timeout=max(0.001, deadline - time.perf_counter()))
            except TimeoutError:
                with self.cond:
                    self.stats["runTimeouts"] += 1
                self.recycle(generation)
                return {"outcome": "run-timeout", "queueWaitMs": queue_ms}
            except (BrokenProcessPool, CancelledError):
                with self.cond:
                    self.stats["workerDeaths"] += 1
                self.recycle(generation)
                return {"outcome": "worker-died", "queueWaitMs": queue_ms}
            with self.cond:
                self.stats["completed"] += 1
            recycled = False
            if recycle_after is not None and recycle_after(res):
                recycled = self.recycle(generation)
            return {"outcome": "ok", "result": res, "queueWaitMs": queue_ms, "recycled": recycled}
        finally:
            with self.cond:
                self.running = None
                self.cond.notify_all()


def _ms_since(t0: float) -> float:
    return round((time.perf_counter() - t0) * 1000.0, 2)


class ConcurrentModuleRegistry:
    """
    Manages warm module imports, pre-compilation, and a high-concurrency ProcessPoolExecutor
    to execute scientific metallurgy & physics computations in parallel across all CPU cores.
    """

    def __init__(self, script_dir: str, num_workers: int = NUM_WORKERS):
        self.script_dir = script_dir
        self.num_workers = num_workers
        self.modules: Dict[str, Any] = {}
        self.compiled_code: Dict[str, Any] = {}
        self.import_times: Dict[str, float] = {}
        self.stats_lock = threading.Lock()
        self.fallback_lock = threading.Lock()
        self.request_count = 0
        self.active_jobs = 0
        self.total_duration_ms = 0.0
        self.start_time = time.time()
        self.pool: Optional[ProcessPoolExecutor] = None
        # One serial lane (single-worker pool + queue) per AFFINITY_SCRIPT_NAMES entry, created on
        # first use or by start_affinity_pools.
        self.affinity_lanes: Dict[str, _AffinityLane] = {}
        self.affinity_lock = threading.Lock()

        self.warmup()
        self._init_pool()

    def warmup(self):
        """Eagerly imports all modules and compiles their source code in master process."""
        sys.stderr.write("[PersistentIPC] Warming up scientific modules in memory...\n")
        t0 = time.time()
        for mod_name in WARM_MODULE_NAMES:
            py_file = os.path.realpath(os.path.join(self.script_dir, f"{mod_name}.py"))
            t_mod0 = time.time()
            try:
                mod = __import__(mod_name)
                self.modules[mod_name] = mod
                if os.path.exists(py_file):
                    with open(py_file, "r", encoding="utf-8") as f:
                        code_str = f.read()
                    compiled = compile(code_str, py_file, "exec")
                    self.compiled_code[py_file] = compiled
                    self.compiled_code[f"python/{mod_name}.py"] = compiled
                    self.compiled_code[f"{mod_name}.py"] = compiled

                dt = (time.time() - t_mod0) * 1000.0
                self.import_times[mod_name] = round(dt, 2)
            except Exception as e:
                sys.stderr.write(f"[PersistentIPC] Warning: Failed to pre-warm {mod_name}: {e}\n")

        total_dt = (time.time() - t0) * 1000.0
        sys.stderr.write(
            f"[PersistentIPC] Successfully loaded {len(self.modules)} modules into RAM in {total_dt:.1f}ms\n"
        )

    def _init_pool(self):
        """Spawns or recycles the multi-process worker pool."""
        try:
            if self.pool:
                try:
                    self.pool.shutdown(wait=False, cancel_futures=True)
                except Exception:
                    pass
            self.pool = ProcessPoolExecutor(
                max_workers=self.num_workers,
                mp_context=_pool_mp_context(),
                initializer=_worker_init,
                initargs=(self.script_dir, WARM_MODULE_NAMES, _parent_uname()),
            )
            sys.stderr.write(
                f"[PersistentIPC] ProcessPoolExecutor initialized with {self.num_workers} warm worker processes.\n"
            )
        except Exception as e:
            sys.stderr.write(f"[PersistentIPC] Worker pool creation error: {e}\n")
            self.pool = None

    def _affinity_name(self, full_path: str) -> Optional[str]:
        name = os.path.splitext(os.path.basename(full_path))[0]
        return name if name in AFFINITY_SCRIPT_NAMES else None

    def _new_affinity_pool(self, name: str) -> ProcessPoolExecutor:
        return ProcessPoolExecutor(
            max_workers=1,
            mp_context=_pool_mp_context(),
            initializer=_worker_init,
            initargs=(self.script_dir, [name], _parent_uname()),
        )

    def _affinity_lane(self, name: str) -> _AffinityLane:
        with self.affinity_lock:
            lane = self.affinity_lanes.get(name)
            if lane is None:
                lane = _AffinityLane(name, lambda: self._new_affinity_pool(name), (_worker_noop, 0.0))
                self.affinity_lanes[name] = lane
            return lane

    def start_affinity_pools(self) -> None:
        """Starts the affinity workers in the background (no wait), so the first request does not
        pay for the process start and imports."""
        for name in sorted(AFFINITY_SCRIPT_NAMES.difference(ISOLATED_SCRIPT_NAMES)):
            try:
                self._affinity_lane(name).prestart()
            except Exception as e:
                sys.stderr.write(f"[PersistentIPC] Affinity pre-start failed for {name}: {e}\n")

    @staticmethod
    def _kill_pool(pool) -> None:
        procs = list((getattr(pool, "_processes", None) or {}).values())
        try:
            pool.shutdown(wait=False, cancel_futures=True)
        except Exception:
            pass
        for proc in procs:
            try:
                proc.terminate()
            except Exception:
                pass

    def _execute_affinity(self, name: str, full_path: str, input_str: str, args: list, timeout_ms: Any,
                          timeout_sec: float, payload: Any, start_time: float) -> Dict[str, Any]:
        lane = self._affinity_lane(name)
        with self.stats_lock:
            self.active_jobs += 1
        try:
            isolated = name in ISOLATED_SCRIPT_NAMES
            out = lane.run((_worker_run_script, full_path, input_str, args), timeout_sec, _supersede_key(payload),
                           recycle_after=_requests_worker_recycle if isolated else None)
        finally:
            with self.stats_lock:
                self.active_jobs = max(0, self.active_jobs - 1)
        duration_ms = round((time.perf_counter() - start_time) * 1000.0, 2)
        base = {"durationMs": duration_ms, "warm": True, "concurrency": f"affinity_pool:{name}",
                "queueWaitMs": out["queueWaitMs"]}
        outcome = out["outcome"]
        if outcome == "ok":
            res = out["result"]
            with self.stats_lock:
                self.request_count += 1
                self.total_duration_ms += duration_ms
            if out.get("recycled"):
                base["workerRecycled"] = True
            return {"stdout": res["stdout"], "stderr": res["stderr"], "exitCode": res["exitCode"], **base}
        if outcome == "superseded":
            # Not an error of the request: a newer request from the same client replaced it before it
            # started. Answered as an explicit, number-free envelope.
            envelope = {"success": False, "status": "superseded",
                        "reason": "superseded by a newer request with the same supersedeKey before it started; "
                                  "not computed"}
            return {"stdout": json.dumps(envelope), "stderr": "", "exitCode": 0, "superseded": True, **base}
        if outcome == "queue-timeout":
            msg = (f"Execution timed out after {timeout_ms}ms (never started: {out['ahead']} {name} job(s) "
                   f"ahead in the queue)")
            stdout = _research_timeout_envelope("queue") if isolated else ""
            return {"stdout": stdout, "stderr": msg, "exitCode": 124, **base}
        if outcome == "run-timeout":
            stdout = _research_timeout_envelope("run") if isolated else ""
            return {"stdout": stdout, "stderr": f"Execution timed out after {timeout_ms}ms "
                                                f"(worker terminated and affinity worker replaced)",
                    "exitCode": 124, **base}
        return {"stdout": "", "stderr": "Worker process died during execution; the request was not re-run.",
                "exitCode": 1, **base}

    def execute_script(
        self,
        script_rel_path: str,
        payload: Any,
        args: Optional[list] = None,
        timeout_ms: int = 15000,
    ) -> Dict[str, Any]:
        """
        Executes a script concurrently in a worker process, bypassing GIL constraints.
        Automatically enforces timeouts and falls back to in-process execution if needed.
        """
        start_time = time.perf_counter()
        args = args or []

        # Resolve path: allowlisted names only, contained in script_dir (no traversal).
        try:
            full_path = resolve_script_path(self.script_dir, script_rel_path)
        except IPCRequestRejected as rejected:
            result = rejected.as_result()
            result["durationMs"] = round((time.perf_counter() - start_time) * 1000.0, 2)
            result["warm"] = True
            return result

        # Prepare JSON input string
        if payload is not None:
            input_str = payload if isinstance(payload, str) else json.dumps(payload)
        else:
            input_str = ""

        timeout_sec = max(1.0, float(timeout_ms) / 1000.0)

        affinity = self._affinity_name(full_path)
        if (affinity and affinity not in ISOLATED_SCRIPT_NAMES
                and _payload_field(payload, "action") in METADATA_ACTIONS):
            affinity = None  # metadata (database list, coverage) never waits behind a calculation
        if affinity:
            return self._execute_affinity(affinity, full_path, input_str, args, timeout_ms, timeout_sec,
                                          payload, start_time)

        with self.stats_lock:
            self.active_jobs += 1

        try:
            # 1. Primary execution via ProcessPoolExecutor
            future = None
            if self.pool is not None:
                try:
                    future = self.pool.submit(_worker_run_script, full_path, input_str, args)
                except (BrokenProcessPool, RuntimeError):
                    # Not submitted, so not executed: recycle and use the in-process path below.
                    sys.stderr.write("[PersistentIPC] Worker pool unusable at submit; recycling...\n")
                    self._init_pool()
                    future = None
            if future is not None:
                try:
                    res = future.result(timeout=timeout_sec)
                    duration_ms = round((time.perf_counter() - start_time) * 1000.0, 2)
                    with self.stats_lock:
                        self.request_count += 1
                        self.total_duration_ms += duration_ms
                    return {
                        "stdout": res["stdout"],
                        "stderr": res["stderr"],
                        "exitCode": res["exitCode"],
                        "durationMs": duration_ms,
                        "warm": True,
                        "concurrency": "process_pool",
                    }
                except TimeoutError:
                    outcome = self._abandon(future)
                    return {
                        "stdout": "",
                        "stderr": f"Execution timed out after {timeout_ms}ms ({outcome})",
                        "exitCode": 124,
                        "durationMs": round((time.perf_counter() - start_time) * 1000.0, 2),
                        "warm": True,
                        "concurrency": "process_pool",
                    }
                except BrokenProcessPool:
                    # The worker died while this job may have been running: never re-run it here.
                    sys.stderr.write("[PersistentIPC] Worker died during execution; recycling pool...\n")
                    self._init_pool()
                    return {
                        "stdout": "",
                        "stderr": "Worker process died during execution; the request was not re-run.",
                        "exitCode": 1,
                        "durationMs": round((time.perf_counter() - start_time) * 1000.0, 2),
                        "warm": True,
                        "concurrency": "process_pool",
                    }

            # 2. Resilient In-Process Fallback if pool is recovering
            with self.fallback_lock:
                compiled = self.compiled_code.get(full_path)
                if not compiled:
                    with open(full_path, "r", encoding="utf-8") as f:
                        compiled = compile(f.read(), full_path, "exec")
                    self.compiled_code[full_path] = compiled

                old_stdin = sys.stdin
                old_stdout = sys.stdout
                old_stderr = sys.stderr
                old_argv = sys.argv

                captured_stdout = io.StringIO()
                captured_stderr = io.StringIO()
                sys.stdin = io.StringIO(input_str)
                sys.stdout = captured_stdout
                sys.stderr = captured_stderr
                sys.argv = [os.path.basename(full_path)] + args

                env = {
                    "__name__": "__main__",
                    "__file__": full_path,
                    "__package__": None,
                }

                exit_code = 0
                try:
                    exec(compiled, env)
                except SystemExit as se:
                    exit_code = se.code if isinstance(se.code, int) else 0
                except Exception:
                    exit_code = 1
                    captured_stderr.write(traceback.format_exc())
                finally:
                    sys.stdin = old_stdin
                    sys.stdout = old_stdout
                    sys.stderr = old_stderr
                    sys.argv = old_argv

                duration_ms = round((time.perf_counter() - start_time) * 1000.0, 2)
                with self.stats_lock:
                    self.request_count += 1
                    self.total_duration_ms += duration_ms

                return {
                    "stdout": captured_stdout.getvalue(),
                    "stderr": captured_stderr.getvalue(),
                    "exitCode": exit_code,
                    "durationMs": duration_ms,
                    "warm": True,
                    "concurrency": "in_process_fallback",
                }
        finally:
            with self.stats_lock:
                self.active_jobs = max(0, self.active_jobs - 1)

    def get_status(self) -> Dict[str, Any]:
        with self.stats_lock:
            req_count = self.request_count
            tot_duration = self.total_duration_ms
            active_jobs = self.active_jobs

        uptime_sec = round(time.time() - self.start_time, 1)
        avg_latency = round(tot_duration / max(1, req_count), 2) if req_count > 0 else 0.0

        return {
            "status": "online",
            "concurrencyModel": "ProcessPoolExecutor",
            "workerCount": self.num_workers,
            "activeJobs": active_jobs,
            "ipcChannels": dict(getattr(self, "channels", {})),
            "warmModules": list(self.modules.keys()),
            "compiledScripts": len(self.compiled_code),
            "requestsProcessed": req_count,
            "avgDurationMs": avg_latency,
            "uptimeSeconds": uptime_sec,
            "pythonVersion": sys.version.split()[0],
            "moduleImportTimesMs": self.import_times,
            "affinityPools": sorted(self.affinity_lanes.keys()),
            "affinityLanes": {name: lane.snapshot() for name, lane in sorted(self.affinity_lanes.items())},
        }

    def _terminate_workers(self):
        """Stops the pool and kills its worker processes (a running job cannot be cancelled)."""
        pool, self.pool = self.pool, None
        if pool is None:
            return
        procs = list((getattr(pool, "_processes", None) or {}).values())
        try:
            pool.shutdown(wait=False, cancel_futures=True)
        except Exception:
            pass
        for proc in procs:
            try:
                proc.terminate()
            except Exception:
                pass

    def _abandon(self, future) -> str:
        """After a timeout: cancel the job if it has not started; otherwise kill and recycle the
        workers when no other job is in flight, else leave it running (reported, not hidden)."""
        if future.cancel():
            return "job cancelled before it started"
        with self.stats_lock:
            others = self.active_jobs - 1
        if others <= 0:
            self._terminate_workers()
            self._init_pool()
            return "worker terminated and pool recycled"
        return f"job left running: {others} other job(s) share the pool"

    def prewarm_pool(self, timeout_s: float = 300.0) -> int:
        """Starts every worker before the service announces readiness; returns the number of distinct workers seen.

        One batch of N short tasks does not guarantee N distinct workers: under load a fast worker can drain two
        tasks before the next process has initialised. Batches are repeated until N distinct PIDs have answered,
        bounded by timeout_s; at the deadline the (smaller) observed count is returned, never an inflated one.
        """
        if self.pool is None:
            return 0
        try:
            deadline = time.monotonic() + timeout_s
            pids = set()
            while len(pids) < self.num_workers:
                futures = [self.pool.submit(_worker_noop, 0.2) for _ in range(self.num_workers)]
                for f in futures:
                    pids.add(f.result(timeout=max(0.001, deadline - time.monotonic())))
                if time.monotonic() >= deadline:
                    break
            return len(pids)
        except Exception as e:
            sys.stderr.write(f"[PersistentIPC] Worker pre-warm failed: {e}\n")
            return 0

    def shutdown(self):
        """Closes the worker pools and terminates their processes (no orphaned workers)."""
        self._terminate_workers()
        with self.affinity_lock:
            lanes, self.affinity_lanes = list(self.affinity_lanes.values()), {}
        for lane in lanes:
            lane.shutdown()


def _is_pool_worker_process() -> bool:
    """True inside a pool worker or the forkserver, where this module is re-imported.

    While a spawn/forkserver child re-imports the main script (as ``__mp_main__``),
    ``multiprocessing.parent_process()`` is still None, so the module name and the
    ``_inheriting`` flag are what identify that import; parent_process() covers the later
    by-name import when a worker unpickles ``_worker_init``.
    """
    return (__name__ == "__mp_main__"
            or bool(getattr(multiprocessing.current_process(), "_inheriting", False))
            or multiprocessing.parent_process() is not None)


