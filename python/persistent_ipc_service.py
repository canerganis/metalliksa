class MicroserviceHTTPHandler(http.server.BaseHTTPRequestHandler):
    """Loopback REST handler. No CORS: browsers are not clients of this service.

    Security configuration lives on the server object (see ThreadedHTTPServer): ``ipc_token``,
    ``allowed_hosts``, ``nonces``, ``preauth`` and ``registry``. One request per connection.
    Requests carry X-Metallix-Ts / -Nonce / -Body-Sha256 / -Mac; the MAC covers method, path, ts,
    nonce, Content-Length and the body hash and is verified before the body is read. Responses
    carry X-Metallix-Body-Sha256 and, for authenticated requests, X-Metallix-Mac.
    """

    timeout = CONNECTION_IDLE_TIMEOUT_S  # per socket operation
    _MAX_DRAIN_BYTES = 64 * 1024

    def log_message(self, format, *args):
        # Silence default access log to keep stdout/stderr clean
        pass

    @property
    def _registry(self) -> "ConcurrentModuleRegistry":
        return getattr(self.server, "registry", None) or registry

    def handle(self):
        """One request per connection, inside a bounded, time-boxed pre-authentication slot."""
        self._auth_nonce = None
        self._body_read = False
        self._sem = getattr(self.server, "preauth", None)
        if self._sem is not None and not self._sem.acquire(blocking=False):
            self._sem = None
            return  # too many unauthenticated connections: close without reading
        self._preauth_open = True
        self._timer = threading.Timer(PREAUTH_DEADLINE_S, self._abort_unauthenticated)
        self._timer.daemon = True
        self._timer.start()
        try:
            self.close_connection = True
            self.handle_one_request()
        except (OSError, ValueError):
            pass  # client went away, or the pre-auth deadline cut the connection
        finally:
            self._end_preauth()

    def _abort_unauthenticated(self):
        if getattr(self, "_preauth_open", False):
            try:
                self.connection.shutdown(socket.SHUT_RDWR)
            except OSError:
                pass

    def _end_preauth(self):
        if getattr(self, "_preauth_open", False):
            self._preauth_open = False
            self._timer.cancel()
            if self._sem is not None:
                self._sem.release()

    def _send_json(self, status_code: int, data: Any):
        body = json.dumps(data).encode("utf-8")
        digest = body_digest(body)
        self.send_response(status_code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("Connection", "close")
        self.send_header("X-Metallix-Body-Sha256", digest)
        nonce = getattr(self, "_auth_nonce", None)
        token = getattr(self.server, "ipc_token", None)
        if nonce and token:
            self.send_header("X-Metallix-Mac", response_mac(token, nonce, status_code, len(body), digest))
        self.end_headers()
        self.wfile.write(body)

    def _reject(self, rejected: IPCRequestRejected):
        # Drain a small unread body first: closing a socket with unread data makes some
        # stacks (Windows) reset the connection before the client reads the error.
        if self.command == "POST" and not self._body_read:
            try:
                pending = int(self.headers.get("Content-Length", 0))
            except ValueError:
                pending = 0
            if 0 < pending <= self._MAX_DRAIN_BYTES:
                try:
                    self.rfile.read(pending)
                except OSError:
                    pass
        self.close_connection = True
        self._send_json(rejected.status, {"error": rejected.message, "code": rejected.code})

    def _authenticate(self, require_json: bool) -> bytes:
        """Head checks and MAC verification (no body byte read), then the hash-checked body."""
        ts, nonce, mac, digest = check_http_headers(
            self.headers, allowed_hosts=getattr(self.server, "allowed_hosts", frozenset()),
            require_json=require_json)
        raw_length = self.headers.get_all("Content-Length") or []
        try:
            length = int(raw_length[0]) if len(raw_length) == 1 else (0 if not raw_length else -1)
        except ValueError:
            length = -1
        if length < 0 or (self.command == "POST" and length == 0) or (self.command != "POST" and length != 0):
            raise IPCRequestRejected(400, "INVALID_LENGTH", "Missing or invalid Content-Length")
        if length > MAX_BODY_BYTES:
            raise IPCRequestRejected(413, "PAYLOAD_TOO_LARGE", f"Body larger than {MAX_BODY_BYTES} bytes")
        verify_request(getattr(self.server, "ipc_token", None), self.command, self.path, ts, nonce, mac,
                       length, digest, self.server.nonces)
        self._auth_nonce = nonce
        self._end_preauth()
        body = read_body_checked(self.rfile.read, length, digest, time.monotonic() + BODY_DEADLINE_S)
        self._body_read = True
        return body

    def do_GET(self):
        try:
            self._authenticate(require_json=False)
        except IPCRequestRejected as rejected:
            return self._reject(rejected)
        if self.path in ["/status", "/health", "/api/status", "/api/health"]:
            self._send_json(200, self._registry.get_status())
        elif self.path == "/ping":
            self._send_json(200, {"pong": True, "timestamp": time.time()})
        else:
            self._send_json(404, {"error": "Endpoint not found", "path": self.path})

    def do_POST(self):
        try:
            body_bytes = self._authenticate(require_json=True)
        except IPCRequestRejected as rejected:
            return self._reject(rejected)
        if self.path in ["/execute", "/run", "/api/execute", "/api/run"]:
            try:
                req = json.loads(body_bytes.decode("utf-8"))
            except Exception as e:
                return self._reject(IPCRequestRejected(400, "INVALID_JSON", f"JSON parse error: {str(e)}"))

            try:
                script, payload, args, timeout_ms = validate_exec_request(req)
                resolve_script_path(self._registry.script_dir, script)
            except IPCRequestRejected as rejected:
                return self._reject(rejected)

            result = self._registry.execute_script(script, payload, args, timeout_ms)
            if "id" in req:
                result["id"] = req["id"]
            self._send_json(200, result)

        elif self.path == "/warmup":
            self._registry.warmup()
            self._send_json(200, self._registry.get_status())
        else:
            self._send_json(404, {"error": "Endpoint not found", "path": self.path})


class ThreadedHTTPServer(socketserver.ThreadingMixIn, http.server.HTTPServer):
    daemon_threads = True
    # On Windows SO_REUSEADDR lets another process bind the same port while we hold it (port
    # stealing); bind with SO_EXCLUSIVEADDRUSE there instead. POSIX SO_REUSEADDR only allows
    # rebinding over TIME_WAIT and is kept.
    allow_reuse_address = os.name != "nt"
    ipc_token: Optional[str] = None
    allowed_hosts: frozenset = frozenset()
    registry: Optional["ConcurrentModuleRegistry"] = None
    nonces: "NonceCache"
    preauth: Optional[threading.BoundedSemaphore] = None

    def handle_error(self, request, client_address):
        # Never print request tracebacks (they could echo request data); one line is enough.
        exc = sys.exc_info()[1]
        if not isinstance(exc, OSError):
            sys.stderr.write(f"[PersistentIPC] HTTP handler error: {exc.__class__.__name__}\n")

    def server_bind(self):
        if os.name == "nt" and hasattr(socket, "SO_EXCLUSIVEADDRUSE"):
            self.socket.setsockopt(socket.SOL_SOCKET, socket.SO_EXCLUSIVEADDRUSE, 1)
        super().server_bind()


class ThreadedHTTPServer6(ThreadedHTTPServer):
    address_family = socket.AF_INET6


def make_http_server(host: str, port: int, token: Optional[str],
                     reg: Optional["ConcurrentModuleRegistry"] = None) -> ThreadedHTTPServer:
    """Builds the HTTP service with its security configuration (port 0 picks a free port).
    IPv6 loopback (::1) gets an AF_INET6 socket."""
    bare = host.strip().strip("[]")
    cls = ThreadedHTTPServer6 if ":" in bare else ThreadedHTTPServer
    httpd = cls((bare, port), MicroserviceHTTPHandler)
    httpd.ipc_token = token
    httpd.allowed_hosts = allowed_host_headers(bare, httpd.server_address[1])
    httpd.nonces = NonceCache()
    httpd.preauth = threading.BoundedSemaphore(PREAUTH_SLOTS)
    httpd.registry = reg
    return httpd


def _http_url(host: str, port: int) -> str:
    h = host.strip("[]")
    return f"http://[{h}]:{port}" if ":" in h else f"http://{h}:{port}"


def _detach_stdin_for_watch() -> None:
    """Moves the supervisor's stdin pipe off fd 0 before any worker process exists.

    On Windows a ``spawn`` child does not finish starting while another thread of its parent holds
    a pending synchronous read on the inherited stdin pipe (the stdin watch thread): the worker
    hangs at interpreter start (review B1: the CALPHAD affinity worker, started after the watch
    thread, never ran a job; a shared-pool recycle during the watch hung the same way). The pipe
    is kept on a duplicated, non-inheritable descriptor that becomes sys.stdin for the watcher;
    fd 0, which children inherit, is pointed at the null device. EOF detection is unchanged.
    """
    try:
        keep = os.dup(0)  # non-inheritable by default (PEP 446)
    except OSError:
        return  # no stdin to watch or to hand down
    null = os.open(os.devnull, os.O_RDONLY)
    try:
        os.dup2(null, 0)
    finally:
        os.close(null)
    sys.stdin = os.fdopen(keep, "r", encoding="utf-8", errors="replace")


def _watch_stdin_eof(on_eof) -> None:
    """Calls on_eof() when stdin reaches EOF (the supervisor that holds the pipe is gone)."""
    def run():
        try:
            stream = sys.stdin.buffer if sys.stdin is not None else None
            while stream is not None and stream.read(65536):
                pass
        except Exception:
            pass
        on_eof()

    threading.Thread(target=run, daemon=True, name="metallix-ipc-stdin-watch").start()


def run_services():
    """Checks the configuration and binds the channels before any warm-up, then serves."""
    global registry
    token = _take_ipc_token()
    validate_startup_config(HTTP_HOST, token)

    # 1. UNIX domain socket IPC (POSIX). Failure is fatal: the supervisor must not believe in a
    #    channel that does not exist, and a silent HTTP-only fallback hides a hostile /tmp.
    ipc_server = None
    if os.name != "nt":
        try:
            sock_path, private_dir = create_socket_path(UNIX_SOCKET_PATH)
            ipc_server = UnixIPCServer(sock_path, None, token, private_dir)
            ipc_server.bind()
        except (OSError, SystemExit) as e:
            if ipc_server is not None:
                ipc_server.stop()
            raise SystemExit(e.code if isinstance(e, SystemExit) else
                             f"[PersistentIPC] Refusing to start: UNIX socket unavailable ({e}).")
    else:
        sys.stderr.write("[PersistentIPC] UNIX socket skipped on Windows; HTTP loopback only.\n")

    # 2. HTTP microservice (Windows always; POSIX with METALLIX_IPC_HTTP=1). Ephemeral port unless
    #    METALLIX_IPC_PORT is set; exclusive bind on Windows; fatal when it is the only channel.
    #    A failed fixed port is reported as inactive, so the supervisor never talks to its holder.
    httpd = None
    if HTTP_ENABLED:
        try:
            httpd = make_http_server(HTTP_HOST, HTTP_PORT, token, None)
        except OSError as e:
            sys.stderr.write(f"[PersistentIPC] HTTP microservice bind error on {HTTP_HOST}:{HTTP_PORT}: {e}\n")
            if ipc_server is None:
                raise SystemExit(f"[PersistentIPC] Refusing to start: no IPC channel could be opened ({e}).")
    del token

    # 3. Warm-up and worker pool only once the channels are ours; workers are started and warmed
    #    before the ready message, so the first request does not pay for them. The stdin pipe is
    #    moved off fd 0 first (B1), so no worker, now or after a recycle, inherits it.
    if STDIN_WATCH:
        _detach_stdin_for_watch()
    if registry is None:
        registry = ConcurrentModuleRegistry(SCRIPT_DIR)
    workers_ready = registry.prewarm_pool()
    registry.start_affinity_pools()
    if ipc_server:
        ipc_server.reg = registry
        ipc_server.serve()
    if httpd:
        httpd.registry = registry

    http_port = httpd.server_address[1] if httpd else None
    http_url = _http_url(HTTP_HOST, http_port) if httpd else None
    if httpd:
        sys.stderr.write(f"[PersistentIPC] HTTP microservice listening at {http_url}\n")
    registry.channels = {"unixSocket": ipc_server.sock_path if ipc_server else None, "httpMicroservice": http_url}

    shutting_down = threading.Lock()

    def shutdown_and_exit(reason: str, code: int = 0):
        if not shutting_down.acquire(blocking=False):
            return
        sys.stderr.write(f"\n[PersistentIPC] {reason}; shutting down cleanly...\n")
        if ipc_server:
            ipc_server.stop()
        registry.shutdown()
        os._exit(code)

    def handle_signal(sig, frame):
        shutdown_and_exit(f"Received signal {sig}")

    signal.signal(signal.SIGTERM, handle_signal)
    signal.signal(signal.SIGINT, handle_signal)
    if STDIN_WATCH:
        _watch_stdin_eof(lambda: shutdown_and_exit("Supervisor gone (stdin closed)"))

    # Inform the supervisor on stdout which channels are really ours and where they are.
    ready_msg = {
        "status": "ready",
        "unixSocket": ipc_server.sock_path if ipc_server else None,
        "http": http_url,
        "httpHost": HTTP_HOST if httpd else None,
        "httpPort": http_port,
        "protocol": PROTOCOL.decode("ascii"),
        "modulesWarm": len(registry.modules),
        "warmModules": list(registry.modules.keys()),
        "pythonVersion": sys.version.split()[0],
        "unixSocketActive": ipc_server is not None,
        "httpActive": httpd is not None,
        "workers": registry.num_workers,
        "workersStarted": workers_ready,
        "concurrency": "ProcessPoolExecutor",
    }
    sys.stdout.write(json.dumps(ready_msg) + "\n")
    sys.stdout.flush()

    try:
        if httpd:
            httpd.serve_forever()
        else:
            while True:
                time.sleep(1)
    finally:
        if ipc_server:
            ipc_server.stop()


if __name__ == "__main__":
    run_services()
