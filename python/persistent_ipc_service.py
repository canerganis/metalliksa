def _payload_field(payload: Any, key: str) -> Any:
    """A top-level field of a JSON-object payload (dict or JSON text), else None."""
    if isinstance(payload, str):
        try:
            payload = json.loads(payload)
        except ValueError:
            return None
    return payload.get(key) if isinstance(payload, dict) else None


def _research_timeout_envelope(timeout_kind: str) -> str:
    """stdout of an isolated-lane timeout (exit 124): the route answers HTTP 504 with this code and kind."""
    return json.dumps({"success": False, "errorKind": "research", "reasonCode": "RESEARCH_TIMEOUT",
                       "timeoutKind": timeout_kind})


def _requests_worker_recycle(result: Any) -> bool:
    """True when a script result's stdout is a JSON object with the top-level flag "recycleWorker": true."""
    stdout = result.get("stdout") if isinstance(result, dict) else None
    if not isinstance(stdout, str) or '"recycleWorker"' not in stdout:
        return False
    try:
        parsed = json.loads(stdout)
    except ValueError:
        return False
    return isinstance(parsed, dict) and parsed.get("recycleWorker") is True


def _supersede_key(payload: Any) -> Optional[str]:
    key = _payload_field(payload, "supersedeKey")
    if isinstance(key, str) and 0 < len(key) <= MAX_SUPERSEDE_KEY_LENGTH:
        return key
    return None

_SCRIPT_FILE_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\.py\Z")
MAX_SCRIPT_ARGS = 64
MAX_TIMEOUT_MS = 600000


class IPCRequestRejected(Exception):
    """A request refused before any script runs; ``status`` is the HTTP status to send."""

    def __init__(self, status: int, code: str, message: str):
        super().__init__(message)
        self.status = status
        self.code = code
        self.message = message

    def as_result(self) -> Dict[str, Any]:
        return {"stdout": "", "stderr": self.message, "exitCode": 1, "error": self.message,
                "code": self.code, "status": self.status}


def _same_dir(a: str, b: str) -> bool:
    return os.path.normcase(os.path.normpath(a)) == os.path.normcase(os.path.normpath(b))


def resolve_script_path(script_dir: str, script: Any,
                        allowed: Iterable[str] = ALLOWED_SCRIPT_NAMES) -> str:
    """Map a request's script reference to an allowlisted file directly inside script_dir.

    Accepted forms are exactly ``python/<name>.py`` and ``<name>.py``. Traversal, absolute
    paths, drive letters, UNC paths, backslashes and nested directories are refused (400);
    names outside the allowlist and symlinks resolving outside script_dir are refused (403).
    """
    if not isinstance(script, str) or not script.strip():
        raise IPCRequestRejected(400, "MISSING_SCRIPT", "Missing script path")
    ref = script.strip()
    if len(ref) > 200 or any(ch in ref for ch in ("\\", ":", "\x00")) or ref.startswith("/"):
        raise IPCRequestRejected(400, "INVALID_SCRIPT_PATH", "Invalid script path")
    parts = ref.split("/")
    if len(parts) == 2 and parts[0] == "python":
        file_name = parts[1]
    elif len(parts) == 1:
        file_name = parts[0]
    else:
        raise IPCRequestRejected(400, "INVALID_SCRIPT_PATH", "Invalid script path")
    if not _SCRIPT_FILE_RE.match(file_name):
        raise IPCRequestRejected(400, "INVALID_SCRIPT_PATH", "Invalid script path")
    if file_name[:-3] not in allowed:
        raise IPCRequestRejected(403, "SCRIPT_NOT_ALLOWED", f"Script not allowed: {file_name}")
    base = os.path.realpath(script_dir)
    full_path = os.path.realpath(os.path.join(base, file_name))
    if not _same_dir(os.path.dirname(full_path), base):
        raise IPCRequestRejected(403, "SCRIPT_OUTSIDE_SCRIPT_DIR",
                                 f"Script resolves outside the scripts directory: {file_name}")
    if not os.path.isfile(full_path):
        raise IPCRequestRejected(404, "SCRIPT_NOT_FOUND", f"Script not found: {script}")
    return full_path


def validate_exec_request(req: Any) -> Tuple[Any, Any, list, int]:
    """Shape checks shared by both channels; returns (script, payload, args, timeout_ms)."""
    if not isinstance(req, dict):
        raise IPCRequestRejected(400, "INVALID_REQUEST", "Request body must be a JSON object")
    args = req.get("args", [])
    if args is None:
        args = []
    if (not isinstance(args, list) or len(args) > MAX_SCRIPT_ARGS
            or not all(isinstance(a, str) for a in args)):
        raise IPCRequestRejected(400, "INVALID_ARGS", "args must be a list of strings")
    timeout_ms = req.get("timeoutMs", 15000)
    if isinstance(timeout_ms, bool) or not isinstance(timeout_ms, (int, float)) \
            or not (0 < timeout_ms <= MAX_TIMEOUT_MS):
        raise IPCRequestRejected(400, "INVALID_TIMEOUT", f"timeoutMs must be in (0, {MAX_TIMEOUT_MS}]")
    return req.get("script", ""), req.get("payload"), args, int(timeout_ms)


# --- Mutual authentication (metallix-ipc-v2) --------------------------------------------
PROTOCOL = b"metallix-ipc-v2"
MAX_CLOCK_SKEW_MS = 120_000
MAX_BODY_BYTES = 64 * 1024 * 1024  # server.ts accepts 50 MB JSON bodies
NONCE_CACHE_MAX = 100_000
_NONCE_RE = re.compile(r"[0-9a-f]{32}\Z")
_HEX64_RE = re.compile(r"[0-9a-f]{64}\Z")
_TS_RE = re.compile(r"[0-9]{1,16}\Z")


def _hmac_hex(token: str, message: bytes) -> str:
    return hmac.new(token.encode("utf-8"), message, hashlib.sha256).hexdigest()


def body_digest(body: bytes) -> str:
    return hashlib.sha256(body).hexdigest()


def request_mac(token: str, method: str, path: str, ts: str, nonce: str, length: int, digest: str) -> str:
    """HMAC over protocol, direction, method, path, timestamp, nonce, body length and SHA-256(body).

    Everything it covers is known from the request head, so it is verified before the body is read.
    """
    msg = "\n".join([PROTOCOL.decode("ascii"), "req", method, path, ts, nonce, str(int(length)), digest])
    return _hmac_hex(token, msg.encode("utf-8"))


def response_mac(token: str, nonce: str, status: int, length: int, digest: str) -> str:
    """HMAC binding a response to the request nonce, so a non-owner cannot forge solver output."""
    msg = "\n".join([PROTOCOL.decode("ascii"), "resp", nonce, str(int(status)), str(int(length)), digest])
    return _hmac_hex(token, msg.encode("ascii"))


def macs_equal(presented: Any, expected: str) -> bool:
    """Constant-time comparison of hex MACs."""
    if not isinstance(presented, str) or not _HEX64_RE.match(presented):
        return False
    return hmac.compare_digest(presented.encode("ascii"), expected.encode("ascii"))


class NonceCache:
    """Remembers authenticated nonces for longer than any timestamp stays acceptable.

    A request is accepted while |now - ts| <= MAX_CLOCK_SKEW_MS, i.e. for at most 2 * skew after
    it is first seen (ts at the +skew edge). Entries live 2 * skew + 1 ms and a nonce is a replay
    while now <= expiry, so a replay at exactly first-seen + 2 * skew is still refused.
    """

    def __init__(self, ttl_ms: int = 2 * MAX_CLOCK_SKEW_MS + 1, max_entries: int = NONCE_CACHE_MAX):
        self.ttl_ms = ttl_ms
        self.max_entries = max_entries
        self._seen: Dict[str, int] = {}
        self._lock = threading.Lock()

    def add_if_new(self, nonce: str, now_ms: int) -> bool:
        with self._lock:
            if len(self._seen) >= self.max_entries:
                self._seen = {n: exp for n, exp in self._seen.items() if exp >= now_ms}
                if len(self._seen) >= self.max_entries:
                    return False  # fail closed under a nonce flood
            if nonce in self._seen and self._seen[nonce] >= now_ms:
                return False
            self._seen[nonce] = now_ms + self.ttl_ms
            return True


def _now_ms() -> int:
    return int(time.time() * 1000)


def check_auth_fields(ts: Any, nonce: Any, mac: Any, digest: Any,
                      now_ms: Optional[int] = None) -> Tuple[str, str, str, str]:
    """Shape and freshness checks of the authentication fields."""
    if not (isinstance(ts, str) and _TS_RE.match(ts) and isinstance(nonce, str) and _NONCE_RE.match(nonce)
            and isinstance(mac, str) and _HEX64_RE.match(mac)
            and isinstance(digest, str) and _HEX64_RE.match(digest)):
        raise IPCRequestRejected(401, "UNAUTHORIZED", "Missing or malformed IPC authentication")
    now = _now_ms() if now_ms is None else now_ms
    if abs(now - int(ts)) > MAX_CLOCK_SKEW_MS:
        raise IPCRequestRejected(401, "STALE_REQUEST", "IPC request timestamp outside the allowed window")
    return ts, nonce, mac, digest


def verify_request(token: Optional[str], method: str, path: str, ts: Any, nonce: Any, mac: Any,
                   length: int, digest: Any, nonces: "NonceCache", now_ms: Optional[int] = None) -> None:
    """Raise 401 unless mac authenticates this request head (incl. body length and hash) and the
    nonce is unused. Needs no body byte. The nonce is recorded only after the MAC verifies, so
    unauthenticated traffic cannot fill the replay cache. Fails closed without a token."""
    now = _now_ms() if now_ms is None else now_ms
    check_auth_fields(ts, nonce, mac, digest, now)
    if not token or not macs_equal(mac, request_mac(token, method, path, ts, nonce, length, digest)):
        raise IPCRequestRejected(401, "UNAUTHORIZED", "Missing or invalid IPC authentication")
    if not nonces.add_if_new(nonce, now):
        raise IPCRequestRejected(401, "REPLAYED_REQUEST", "IPC request nonce was already used")


def read_body_checked(read, length: int, digest: str, deadline: float, chunk: int = 64 * 1024) -> bytes:
    """Streams exactly `length` bytes through `read(n)` (already authenticated head) and checks the
    SHA-256. Memory grows with bytes actually received, never with the declared length."""
    buf = bytearray()
    h = hashlib.sha256()
    while len(buf) < length:
        if time.monotonic() > deadline:
            raise IPCRequestRejected(408, "REQUEST_TIMEOUT", "IPC request body not received in time")
        part = read(min(chunk, length - len(buf)))
        if not part:
            raise IPCRequestRejected(400, "TRUNCATED_BODY", "IPC request body ended early")
        h.update(part)
        buf += part
    if not hmac.compare_digest(h.hexdigest(), digest):
        raise IPCRequestRejected(400, "BODY_HASH_MISMATCH", "IPC request body does not match its hash")
    return bytes(buf)


def is_loopback_host(host: str) -> bool:
    if host.strip().lower() == "localhost":
        return True
    try:
        return ipaddress.ip_address(host.strip().strip("[]")).is_loopback
    except ValueError:
        return False


def allowed_host_headers(bind_host: str, port: int) -> frozenset:
    """Host header values accepted by the HTTP service (anything else: DNS rebinding)."""
    hosts = {f"127.0.0.1:{port}", f"localhost:{port}", f"[::1]:{port}"}
    h = bind_host.strip().lower()
    hosts.add(f"[{h.strip('[]')}]:{port}" if ":" in h.strip("[]") else f"{h}:{port}")
    return frozenset(hosts)


def _single_header(headers: Any, name: str) -> Optional[str]:
    values = headers.get_all(name) or []
    return values[0].strip() if len(values) == 1 else None


def check_http_headers(headers: Any, *, allowed_hosts: Iterable[str], require_json: bool,
                       now_ms: Optional[int] = None) -> Tuple[str, str, str, str]:
    """Host, Origin, auth-field and Content-Type checks; returns (ts, nonce, mac, body digest).

    The MAC is verified next (verify_request) from the head alone, before the body is read.
    """
    host = _single_header(headers, "Host")
    if host is None or host.lower() not in allowed_hosts:
        raise IPCRequestRejected(403, "HOST_NOT_ALLOWED", "Host header not allowed")
    if headers.get("Origin") is not None:
        raise IPCRequestRejected(403, "ORIGIN_NOT_ALLOWED", "Browser-originated requests are not allowed")
    auth = check_auth_fields(_single_header(headers, "X-Metallix-Ts"), _single_header(headers, "X-Metallix-Nonce"),
                             _single_header(headers, "X-Metallix-Mac"),
                             _single_header(headers, "X-Metallix-Body-Sha256"), now_ms)
    if require_json:
        media_type = (headers.get("Content-Type") or "").split(";", 1)[0].strip().lower()
        if media_type != "application/json":
            raise IPCRequestRejected(415, "UNSUPPORTED_MEDIA_TYPE", "Content-Type must be application/json")
    return auth


def validate_startup_config(host: str, token: Optional[str]) -> None:
    """Refuse to serve without a usable token or on anything but a loopback address."""
    if not token or len(token) < MIN_TOKEN_LENGTH:
        raise SystemExit(
            f"[PersistentIPC] Refusing to start: METALLIX_IPC_TOKEN must be set (>= {MIN_TOKEN_LENGTH} "
            "characters). The Node supervisor generates it; set it yourself when launching by hand.")
    if not is_loopback_host(host):
        raise SystemExit(
            f"[PersistentIPC] Refusing to bind METALLIX_IPC_HOST={host!r}: only loopback addresses "
            "(127.0.0.1, localhost, ::1) are allowed; the IPC service has no remote clients.")

