/**
 * Storage key for custom user-created builds and records
 */
export const USER_LPBF_DATA_STORAGE_KEY = "metallix_user_lpbf_data_records_v1";

export function loadUserLPBFRecords(): TraceableLPBFRecord[] {
  if (typeof window === "undefined") return [];
  try {
    const raw = localStorage.getItem(USER_LPBF_DATA_STORAGE_KEY);
    if (!raw) return [];
    return JSON.parse(raw);
  } catch (err) {
    console.error("Failed to load user LPBF records:", err);
    return [];
  }
}

export function saveUserLPBFRecords(records: TraceableLPBFRecord[]): void {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(USER_LPBF_DATA_STORAGE_KEY, JSON.stringify(records));
  } catch (err) {
    console.error("Failed to save user LPBF records:", err);
  }
}
