import {
  TraceableLPBFRecord,
  calculateLinearEnergyDensity,
  calculateArealEnergyDensity,
  calculateVolumetricEnergyDensity,
  calculatePeakLaserIntensity,
  classifyProcessRegime,
  LPBFAlloyId,
} from "../types/lpbfDataFoundation";

/**
 * Helper to generate a fully derived TraceableLPBFRecord
 */
function createTraceableRecord(params: {
  id: string;
  buildJobName: string;
  alloyId: LPBFAlloyId;
  alloyName: string;
  machineModel: string;
  powderLotNumber: string;
  powderAtomization: "Gas Atomized (GA)" | "Plasma Atomized (PA)" | "PREP";
  powderD10_um: number;
  powderD50_um: number;
  powderD90_um: number;
  buildDate: string;
  facility: string;
  // Process Params
  laserPower_W: number;
  scanSpeed_mm_s: number;
  hatchSpacing_um: number;
  layerThickness_um: number;
  beamSpotDiameter_um: number;
  scanStrategy: "Meander (67° alternating rotation)" | "Stripe (5mm width, 90° rotation)" | "Island / Checkerboard (5x5mm)" | "Unidirectional Continuous" | "Bidirectional (0°/90°)";
  baseplatePreheat_C: number;
  chamberAtmosphere: string;
  opticalAbsorptivity: number;
  // Sample
  sampleCode: string;
  locationOnPlate: { x_mm: number; y_mm: number; z_mm: number };
  buildOrientationDeg: 0 | 45 | 90;
  heatTreatment: "As-Built" | "Stress Relieved (SR)" | "Hot Isostatic Pressed (HIP)" | "Solution Treated & Aged (STA)" | "Annealed";
  specimenGeometry: "Cylindrical Tensile (ASTM E8)" | "Flat Dogbone" | "Cubic Density (10x10x10mm)" | "Charpy Impact" | "Metallographic Coupon";
  // Properties
  relativeDensity_pct: number;
  porosity_pct: number;
  densityMeasurementMethod: "Archimedes (ASTM B962)" | "Optical Microscopy Image Analysis (ASTM E1245)" | "X-ray Micro-Computed Tomography (Micro-CT)";
  yieldStrength_MPa?: number;
  ultimateTensileStrength_MPa?: number;
  elongationAtBreak_pct?: number;
  reductionOfArea_pct?: number;
  hardness_value?: number;
  hardness_scale?: "HV0.3" | "HV0.5" | "HV1" | "HV5" | "HV10" | "HRC";
  youngsModulus_GPa?: number;
  fatigueLimit_MPa?: number;
  defectMorphology?: "Dense (<0.1% pores)" | "Lack of Fusion (irregular, un-melted powder)" | "Keyhole Pores (spherical, root of melt pool)" | "Gas Porosity / Balling";
  microstructureDescription?: string;
  // Source
  sourceType: "literature" | "experimental" | "internal_qualification";
  citation: string;
  title: string;
  authors: string;
  journal: string;
  year: number;
  doi: string;
  testingStandards: string[];
  labOrganization: string;
}): TraceableLPBFRecord {
  const led = calculateLinearEnergyDensity(params.laserPower_W, params.scanSpeed_mm_s);
  const aed = calculateArealEnergyDensity(params.laserPower_W, params.scanSpeed_mm_s, params.hatchSpacing_um);
  const ved = calculateVolumetricEnergyDensity(params.laserPower_W, params.scanSpeed_mm_s, params.hatchSpacing_um, params.layerThickness_um);
  const intensity = calculatePeakLaserIntensity(params.laserPower_W, params.beamSpotDiameter_um);
  const regime = classifyProcessRegime(ved, params.laserPower_W, params.scanSpeed_mm_s, params.alloyId);

  return {
    id: params.id,
    build: {
      id: `bld-${params.id}`,
      buildJobName: params.buildJobName,
      alloyId: params.alloyId,
      alloyName: params.alloyName,
      machineModel: params.machineModel,
      powderLotNumber: params.powderLotNumber,
      powderAtomization: params.powderAtomization,
      powderD10_um: params.powderD10_um,
      powderD50_um: params.powderD50_um,
      powderD90_um: params.powderD90_um,
      buildDate: params.buildDate,
      facility: params.facility,
    },
    params: {
      id: `par-${params.id}`,
      laserPower_W: params.laserPower_W,
      scanSpeed_mm_s: params.scanSpeed_mm_s,
      hatchSpacing_um: params.hatchSpacing_um,
      layerThickness_um: params.layerThickness_um,
      beamSpotDiameter_um: params.beamSpotDiameter_um,
      scanStrategy: params.scanStrategy,
      baseplatePreheat_C: params.baseplatePreheat_C,
      chamberAtmosphere: params.chamberAtmosphere,
      opticalAbsorptivity: params.opticalAbsorptivity,
      derived: {
        linearEnergyDensity_J_mm: led,
        arealEnergyDensity_J_mm2: aed,
        volumetricEnergyDensity_J_mm3: ved,
        peakLaserIntensity_MW_cm2: intensity,
        // normalizedEnthalpy_dH_hs is not computed in the UI: ΔH/h_s comes from Python only (B5 step 1).
        predictedRegime: regime,
      },
    },
    sample: {
      id: `smp-${params.id}`,
      sampleCode: params.sampleCode,
      locationOnPlate: params.locationOnPlate,
      buildOrientationDeg: params.buildOrientationDeg,
      heatTreatment: params.heatTreatment,
      specimenGeometry: params.specimenGeometry,
    },
    properties: {
      id: `prp-${params.id}`,
      relativeDensity_pct: params.relativeDensity_pct,
      porosity_pct: params.porosity_pct,
      densityMeasurementMethod: params.densityMeasurementMethod,
      yieldStrength_MPa: params.yieldStrength_MPa,
      ultimateTensileStrength_MPa: params.ultimateTensileStrength_MPa,
      elongationAtBreak_pct: params.elongationAtBreak_pct,
      reductionOfArea_pct: params.reductionOfArea_pct,
      hardness_value: params.hardness_value,
      hardness_scale: params.hardness_scale,
      youngsModulus_GPa: params.youngsModulus_GPa,
      fatigueLimit_MPa: params.fatigueLimit_MPa,
      defectMorphology: params.defectMorphology,
      microstructureDescription: params.microstructureDescription,
    },
    source: {
      id: `src-${params.id}`,
      sourceType: params.sourceType,
      citation: params.citation,
      title: params.title,
      authors: params.authors,
      journal: params.journal,
      year: params.year,
      doi: params.doi,
      url: `https://doi.org/${params.doi}`,
      testingStandards: params.testingStandards,
      labOrganization: params.labOrganization,
    },
  };
}

